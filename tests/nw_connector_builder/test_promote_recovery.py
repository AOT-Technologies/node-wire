"""Promote commit point and recovery from an interrupted promote (4.4)."""

from __future__ import annotations

import logging
from pathlib import Path
from unittest.mock import patch

import pytest

from nw_connector_builder.promote import (
    PromoteError,
    assert_generator_owned,
    promote,
    recover_interrupted_promote,
)

MARKER = '"""Generated by nw-connector-builder."""\n'
CID = "pet_store"


def _tree(root: Path, text: str) -> tuple[Path, Path]:
    src = root / "src" / f"node_wire_{CID}"
    pkg = root / "packages" / "connectors" / CID
    src.mkdir(parents=True)
    pkg.mkdir(parents=True)
    (src / "logic.py").write_text(MARKER + text, encoding="utf-8")
    (pkg / "pyproject.toml").write_text(f"# {text}\n", encoding="utf-8")
    return src, pkg


def _sibling(path: Path, suffix: str) -> Path:
    return path.with_name(path.name + suffix)


def test_a_cleanup_failure_after_commit_does_not_roll_back(
    tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    root = tmp_path / "root"
    _tree(root, "old")
    staging = tmp_path / "staging"
    src_stage, _ = _tree(staging, "new")

    with (
        patch("nw_connector_builder.promote._cleanup_backup", side_effect=OSError("busy")),
        caplog.at_level(logging.WARNING),
    ):
        promote(staging, root, CID, force=True)

    logic = root / "src" / f"node_wire_{CID}" / "logic.py"
    assert "new" in logic.read_text(encoding="utf-8")
    assert "busy" in caplog.text


def test_interrupted_before_any_rename_restores_the_previous_trees(tmp_path: Path) -> None:
    root = tmp_path / "root"
    src, pkg = _tree(root, "old")
    for dest in (src, pkg):
        dest.rename(_sibling(dest, ".bak"))
        _sibling(dest, ".promoting").mkdir()

    recover_interrupted_promote(root, CID)

    assert "old" in (src / "logic.py").read_text(encoding="utf-8")
    assert "old" in (pkg / "pyproject.toml").read_text(encoding="utf-8")
    for dest in (src, pkg):
        assert not _sibling(dest, ".bak").exists()
        assert not _sibling(dest, ".promoting").exists()


def test_interrupted_between_the_two_renames_rolls_back_both(tmp_path: Path) -> None:
    root = tmp_path / "root"
    src, pkg = _tree(root, "old")
    src.rename(_sibling(src, ".bak"))
    pkg.rename(_sibling(pkg, ".bak"))
    src.mkdir()  # the new src tree, already renamed into place
    (src / "logic.py").write_text(MARKER + "new", encoding="utf-8")
    _sibling(pkg, ".promoting").mkdir()

    recover_interrupted_promote(root, CID)

    assert "old" in (src / "logic.py").read_text(encoding="utf-8")
    assert "old" in (pkg / "pyproject.toml").read_text(encoding="utf-8")


def test_interrupted_after_both_renames_keeps_the_new_trees(tmp_path: Path) -> None:
    root = tmp_path / "root"
    src, pkg = _tree(root, "new")
    for dest in (src, pkg):
        backup = _sibling(dest, ".bak")
        backup.mkdir()
        (backup / "old.txt").write_text("old", encoding="utf-8")
    (_sibling(pkg, ".bak") / "dist").mkdir()
    (_sibling(pkg, ".bak") / "dist" / "w-1.0-py3-none-any.whl").write_bytes(b"w")

    recover_interrupted_promote(root, CID)

    assert "new" in (src / "logic.py").read_text(encoding="utf-8")
    assert (pkg / "dist" / "w-1.0-py3-none-any.whl").is_file()  # build output carried over
    assert not _sibling(src, ".bak").exists() and not _sibling(pkg, ".bak").exists()


def test_a_missing_logic_py_with_a_hand_written_backup_is_not_owned(tmp_path: Path) -> None:
    root = tmp_path / "root"
    backup = root / "src" / f"node_wire_{CID}.bak"
    backup.mkdir(parents=True)
    (backup / "logic.py").write_text("# hand-written connector\n", encoding="utf-8")

    with pytest.raises(PromoteError, match="not written by nw-connector-builder"):
        assert_generator_owned(root, CID)


def test_promote_recovers_a_leftover_before_starting(tmp_path: Path) -> None:
    root = tmp_path / "root"
    src, pkg = _tree(root, "old")
    src.rename(_sibling(src, ".bak"))  # an earlier promote died after moving src aside
    staging = tmp_path / "staging"
    _tree(staging, "new")

    promote(staging, root, CID, force=True)

    assert "new" in (src / "logic.py").read_text(encoding="utf-8")
    assert not _sibling(src, ".bak").exists()
